"""Dedicated persistence port; no email, model, catalogue or stock dependency."""
from typing import Protocol
from stockpilot.domain.entities.tenant_authorization import TenantContext
from stockpilot.domain.entities.tenant_contact import CreateContact, ReplyContact, SetContactStatus, ContactQuery


class ContactRateLimited(Exception):
    """Persistent tenant/user quota reached."""
    retry_after = 600


class TenantContactPort(Protocol):
    def create(self, request: object, context: TenantContext, command: CreateContact) -> dict: ...
    def list(self, request: object, context: TenantContext, query: ContactQuery) -> dict: ...
    def get(self, request: object, context: TenantContext, request_id: str) -> dict: ...
    def replies(self, request: object, context: TenantContext, request_id: str, limit: int, offset: int) -> dict: ...
    def reply(self, request: object, context: TenantContext, command: ReplyContact) -> dict: ...
    def set_status(self, request: object, context: TenantContext, command: SetContactStatus) -> dict: ...
