import { test, expect } from '@playwright/test'
import { randomUUID } from 'node:crypto'
import { resolve } from 'node:path'
import { mkdirSync } from 'node:fs'
import { connectCustomer, syntheticCustomerToken } from '../e2e/support/customer_auth'

async function login(page: import('@playwright/test').Page) {
  await page.goto('/admin/login')
  await page.getByLabel('Identifiant administrateur').fill(process.env.E2E_ADMIN_USERNAME!)
  await page.getByLabel('Mot de passe administrateur').fill(process.env.E2E_ADMIN_PASSWORD!)
  await page.getByRole('button', { name: 'Se connecter', exact: true }).click()
  await expect(page).toHaveURL(/admin\/orders/)
}

test('real form validation, CSV preview, exact pagination, SKU filters and URL history', async ({ page }) => {
  mkdirSync(resolve('../artifacts/ui-ux/after'), { recursive: true })
  if (process.env.MONGO_DATABASE !== 'stockpilot_e2e') throw new Error('Exact isolated E2E target required')
  await login(page)
  const sampleOrder = await page.evaluate(async () => (await (await fetch('/api/backoffice/orders?limit=1')).json()).items[0])
  if (!sampleOrder) throw new Error('Existing E2E order required for search validation')
  await page.getByLabel('Recherche commandes', { exact: true }).fill(sampleOrder.order_id)
  await page.getByRole('button', { name: 'Rechercher', exact: true }).click()
  await expect(page.locator('tbody tr')).toHaveCount(1)
  await expect(page.getByText('Page 1 sur 1', { exact: true })).toBeVisible()
  await page.getByLabel('Recherche commandes', { exact: true }).fill('no-matching-order-' + randomUUID())
  await page.getByRole('button', { name: 'Rechercher', exact: true }).click()
  await expect(page.getByText('Aucune commande sur cette page.', { exact: true })).toBeVisible()
  await expect(page.getByText('Page 0 sur 0', { exact: true })).toBeVisible()
  await page.goto('/admin/products/new')
  await page.getByRole('button', { name: 'Créer', exact: true }).click()
  expect(await page.locator('#product-sku').evaluate(input => (input as HTMLInputElement).validity.valueMissing)).toBe(true)
  // Append one small, uniquely owned CSV batch through the actual authenticated UI.
  const tag = `UX-${randomUUID()}`
  const csv = 'sku,name,category,price\n' + Array.from({ length: 23 }, (_, index) => `${tag}-${String(index).padStart(2, '0')},Outil UX ${tag.slice(3, 11)} ${index},DRILL,${index + 1}`).join('\n')
  await page.goto('/admin/products/import')
  await page.getByLabel('Fichier CSV').setInputFiles({ name: 'ux-pagination.csv', mimeType: 'text/csv', buffer: Buffer.from(csv) })
  await page.getByRole('button', { name: 'Prévisualiser', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Aperçu', exact: true })).toBeVisible()
  await expect(page.getByRole('button', { name: 'Confirmer l’import' })).toBeDisabled()
  for (const width of [1440, 768, 390]) {
    await page.setViewportSize({ width, height: 1000 })
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
    await page.screenshot({ path: resolve('../artifacts/ui-ux/after', `import-preview-${width}.png`), fullPage: true })
  }
  await page.getByLabel('Je confirme la création de tous ces nouveaux produits sans mise à jour.').check()
  await page.getByRole('button', { name: 'Confirmer l’import' }).click()
  await expect(page.getByRole('heading', { name: 'Import confirmé par le serveur' })).toBeVisible()
  await page.goto(`/products?q=${tag}`)
  await connectCustomer(page, syntheticCustomerToken('ux-catalogue-' + randomUUID()))
  await expect(page.getByText('Page 1 sur 2', { exact: true })).toBeVisible()
  await expect(page.getByText('Affichage de 1 à 20 sur 23 produits', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Dernière page', exact: true }).click()
  await expect(page).toHaveURL(/offset=20/)
  await expect(page.getByRole('article')).toHaveCount(3)
  await expect(page.getByText('Page 2 sur 2', { exact: true })).toBeVisible()
  await expect(page.getByRole('button', { name: 'Suivant', exact: true })).toBeDisabled()
  await page.getByRole('button', { name: 'Première page', exact: true }).click()
  await expect(page).not.toHaveURL(/offset=/)
  await page.getByLabel('Par page', { exact: true }).selectOption('10')
  await expect(page.getByText('Page 1 sur 3', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Page 2', exact: true }).click()
  await expect(page).toHaveURL(/offset=10/)
  await page.goBack()
  await expect(page.getByText('Page 1 sur 3', { exact: true })).toBeVisible()
  await page.goForward()
  await expect(page.getByText('Page 2 sur 3', { exact: true })).toBeVisible()
  await page.getByLabel('Recherche', { exact: true }).fill(`${tag}-00`)
  await page.getByLabel('Catégorie', { exact: true }).selectOption('DRILL')
  await page.getByLabel('Disponibilité', { exact: true }).selectOption('false')
  await page.getByRole('button', { name: 'Rechercher', exact: true }).click()
  await expect(page).not.toHaveURL(/offset=/)
  await expect(page.getByText('Affichage de 1 à 1 sur 1 produits', { exact: true })).toBeVisible()
  await page.getByLabel('Disponibilité', { exact: true }).selectOption('true')
  await page.getByRole('button', { name: 'Rechercher', exact: true }).click()
  await expect(page.getByText('Aucun produit ne correspond à vos critères.', { exact: true })).toBeVisible()
  await expect(page.getByText('Page 0 sur 0', { exact: true })).toBeVisible()
  await page.goto(`/admin/products?q=${tag}`)
  await expect(page.getByText('Page 1 sur 2', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Dernière page', exact: true }).click()
  await expect(page.locator('tbody tr')).toHaveCount(3)
  await page.getByRole('button', { name: 'Première page', exact: true }).click()
  await expect(page.locator('tbody tr')).toHaveCount(20)
})

test('mobile keyboard menu, error / loading states and stale response invalidation', async ({ page }) => {
  mkdirSync(resolve('../artifacts/ui-ux/after'), { recursive: true })
  await page.setViewportSize({ width: 390, height: 900 })
  await page.goto('/products')
  await connectCustomer(page, syntheticCustomerToken('ux-mobile-' + randomUUID()))
  await page.getByRole('button', { name: 'Menu', exact: true }).focus()
  await page.keyboard.press('Enter')
  await expect(page.getByRole('button', { name: 'Fermer le menu' })).toHaveAttribute('aria-expanded', 'true')
  await page.keyboard.press('Tab')
  await expect(page.getByRole('link', { name: 'Catalogue', exact: true })).toBeFocused()
  await page.keyboard.press('Escape')
  await expect(page.getByRole('button', { name: 'Menu', exact: true })).toBeFocused()
  let release: (() => void) | undefined
  await page.route('**/api/products?*', async route => {
    if (new URL(route.request().url()).searchParams.get('q') === 'delayed') {
      await new Promise<void>(resolve => { release = resolve })
      try { await route.continue() } catch { /* navigation can cancel the old request */ }
    } else await route.continue()
  })
  await page.getByLabel('Recherche', { exact: true }).fill('delayed')
  await page.getByRole('button', { name: 'Rechercher', exact: true }).click()
  await expect(page.getByText('Chargement du catalogue...', { exact: true })).toBeVisible()
  await page.screenshot({ path: resolve('../artifacts/ui-ux/after/loading-390.png'), fullPage: true })
  await page.getByLabel('Recherche', { exact: true }).fill('X100')
  // Debounce applies new criteria even while the previous request is pending.
  await expect(page).toHaveURL(/q=X100/)
  await expect(page.getByRole('article')).toHaveCount(1)
  release?.()
  await expect(page.getByRole('heading', { name: 'Bosch X100', exact: true })).toBeVisible()
  await page.unroute('**/api/products?*')
  await page.route('**/api/products?*', route => route.fulfill({ status: 503, contentType: 'application/json', body: '{"detail":"Unavailable"}' }))
  await page.getByRole('button', { name: 'Actualiser', exact: true }).click()
  await expect(page.getByRole('alert')).toBeVisible()
  await expect(page.getByRole('article')).toHaveCount(0)
  await page.screenshot({ path: resolve('../artifacts/ui-ux/after/error-390.png'), fullPage: true })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
})


test('real catalogue recommendations remain readable at every viewport', async ({ page }) => {
  const jwt = syntheticCustomerToken('ux-advice-' + randomUUID())
  await page.goto('/assistant')
  await page.getByLabel('JWT client', { exact: true }).fill(jwt)
  await page.getByRole('button', { name: 'Connecter', exact: true }).click()
  await page.getByLabel('Votre message', { exact: true }).fill('Propose-moi trois perceuses disponibles avec un budget de 150 euros.')
  await page.getByRole('button', { name: 'Envoyer', exact: true }).click()
  await expect(page.getByRole('article', { name: 'Produit recommandé' }).first()).toBeVisible({ timeout: 120_000 })
  const cards = page.getByRole('article', { name: 'Produit recommandé' })
  expect(await cards.count()).toBeGreaterThanOrEqual(1)
  expect(await cards.count()).toBeLessThanOrEqual(3)
  for (const width of [1440, 768, 390]) {
    await page.setViewportSize({ width, height: 1000 })
    await expect(cards.first().getByRole('link')).toHaveAttribute('href', /^\/products\//)
    await expect(cards.first()).toHaveCSS('padding', '16px')
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
    await page.screenshot({ path: resolve('../artifacts/ui-ux/after', `advice-${width}.png`), fullPage: true })
  }
})
